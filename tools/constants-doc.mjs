// Writes docs/constants.md from the constant registry (src/rules/constants.ts): every registered number with its value,
// unit, status, source and range, so the document and the code cannot disagree. Usage: node tools/constants-doc.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
globalThis.fetch = async u => ({ json: async () => JSON.parse(readFileSync(new URL(u))) });
globalThis.SillyTavern ??= { getContext: () => ({ chat: [], chatMetadata: {} }) };
const C = await import('../src/rules/constants.js');
// Load every module that registers constants.
for (const f of readdirSync(new URL('../src/rules/', import.meta.url)).filter(f => f.endsWith('.js'))) {
    const src = readFileSync(new URL(`../src/rules/${f}`, import.meta.url), 'utf8');
    if (src.includes('def({')) await import(`../src/rules/${f}`);
}
const rows = [...C.REGISTRY_K.values()].sort((a, b) => a.file.localeCompare(b.file) || a.id.localeCompare(b.id));
const count = s => rows.filter(r => r.status === s).length;
const md = `# Constants

Generated by \`node tools/constants-doc.mjs\` from the registry in \`src/rules/constants.ts\`; do not edit by hand.
${rows.length} constants: ${count('sourced')} sourced, ${count('fitted')} fitted, ${count('assumed')} assumed, ${count('raw')} raw.
Assumed and fitted ones carry a range; a call that uses them is rerun at both ends and reports when its outcome changes ("Fragile").

| Constant | Value | Unit | Status | Range | Source | File |
|---|---|---|---|---|---|---|
${rows.map(r => `| ${r.id} | ${r.value} | ${r.unit} | ${r.status} | ${r.range ? r.range.join('–') : ''} | ${r.src} | ${r.file} |`).join('\n')}
`;
writeFileSync(new URL('../docs/constants.md', import.meta.url), md);
console.log(`docs/constants.md: ${rows.length} constants`);
